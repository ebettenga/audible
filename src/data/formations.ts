export function findFormation(token: string): Formation | undefined {
  const t = token.toLowerCase().trim();
  return FORMATIONS.find(
    (f) =>
      f.id === t ||
      f.name.toLowerCase() === t ||
      f.aliases.some((a) => a.toLowerCase() === t),
  );
}

/** Multi-word formation match against remaining tokens (longest first). */
export function matchFormation(
  tokens: string[],
  start: number,
): { formation: Formation; consumed: number } | undefined {
  const remaining = tokens.slice(start);
  // Try 3 words, then 2, then 1
  for (let len = Math.min(3, remaining.length); len >= 1; len--) {
    const phrase = remaining.slice(0, len).join(' ');
    const formation = findFormation(phrase);
    if (formation) return { formation, consumed: len };
  }
  return undefined;
}
