/** Scheme themes for play-call questions; shown on the quiz card so patterns repeat across systems. */
export const PLAY_CALL_THEMES = {
  'west-coast': 'West Coast',
  'air-coryell': 'Air Coryell',
  'erhardt-perkins': 'Erhardt-Perkins',
  'air-raid': 'Air Raid',
  'wide-zone-system': 'Shanahan Wide Zone',
  'spread-rpo': 'Spread & RPO',
  'run-and-shoot': 'Run and Shoot',
  option: 'Option Football',
  'wing-t': 'Wing-T',
  pistol: 'Pistol',
  'gap-power': 'Gap & Power',
  protection: 'Protection',
  tempo: 'Tempo & Signals',
  motion: 'Motion & Shifts',
} as const;

export type PlayCallTheme = keyof typeof PLAY_CALL_THEMES;

function fact(
  theme: PlayCallTheme,
  id: string,
  playcall: string,
  prompt: string,
  answer: string,
  distractors: [string, string, string],
  explain: string,
): QuizFact {
  return {
    id: `scheme-${id}`,
    topic: 'play-calls',
    type: 'match-playcall',
    prompt,
    answer,
    distractors,
    explain,
    group: theme,
    theme: PLAY_CALL_THEMES[theme],
    playcall,
  };
}

